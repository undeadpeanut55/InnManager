using InnManager.Enums;
using System;
using System.Collections.Generic;
using System.ComponentModel;
using System.Text;

namespace InnManager.Guests
{
    /// <summary>
    /// Represents a guest staying at a hotel
    /// </summary>
    public class Guest : INotifyPropertyChanged
    {
        public event PropertyChangedEventHandler? PropertyChanged;

        /// <summary>
        /// The guest's first name
        /// </summary>
        public string FirstName
        {
            get;
            set
            {
                FirstName = value;
                PropertyChanged?.Invoke(this, new PropertyChangedEventArgs(nameof(FirstName)));
            }
        } = string.Empty;

        /// <summary>
        /// The guest's last name
        /// </summary>
        public string LastName
        {
            get;
            set
            {
                LastName = value;
                PropertyChanged?.Invoke(this, new PropertyChangedEventArgs(nameof(LastName)));
            }
        } = string.Empty;

        /// <summary>
        /// The guest's email
        /// </summary>
        public string Email
        {
            get;
            set
            {
                Email = value;
                PropertyChanged?.Invoke(this, new PropertyChangedEventArgs(nameof(Email)));
            }
        } = string.Empty;

        /// <summary>
        /// The guest's phone number as a string
        /// </summary>
        public string PhoneNumber
        {
            get;
            set
            {
                PhoneNumber = value;
                PropertyChanged?.Invoke(this, new PropertyChangedEventArgs(nameof(PhoneNumber)));
            }
        } = string.Empty;

        /// <summary>
        /// If the guest has checked in
        /// </summary>
        public bool IsCheckedIn
        {
            get;
            set
            {
                IsCheckedIn = value;
                PropertyChanged?.Invoke(this, new PropertyChangedEventArgs(nameof(IsCheckedIn)));
            }
        } = false;

        /// <summary>
        /// An autogenerated ID number to identify individual guests
        /// </summary>
        public string GuestID
        {
            get;
            set
            {
                GuestID = value;
                PropertyChanged?.Invoke(this, new PropertyChangedEventArgs(nameof(GuestID)));
            }
        } = string.Empty;

        /// <summary>
        /// The address of the guest
        /// </summary>
        public string Address
        {
            get;
            set
            {
                Address = value;
                PropertyChanged?.Invoke(this, new PropertyChangedEventArgs(nameof(Address)));
            }
        } = string.Empty;

        /// <summary>
        /// What type of ID the guest used
        /// </summary>
        public IDType IDType
        {
            get;
            set
            {
                IDType = value;
                PropertyChanged?.Invoke(this, new PropertyChangedEventArgs(nameof(IDType)));
            }
        } = IDType.Other;

        /// <summary>
        /// The number associated with the ID used by the guest
        /// </summary>
        public string IDNumber
        {
            get;
            set
            {
                IDNumber = value;
                PropertyChanged?.Invoke(this, new PropertyChangedEventArgs(nameof(IDNumber)));
            }
        } = string.Empty;



    }
}
