using InnManager.Enums;
using System;
using System.Collections.Generic;
using System.Text;

namespace InnManager.Guests
{
    /// <summary>
    /// Represents a guest staying at a hotel
    /// </summary>
    public class Guest
    {
        /// <summary>
        /// The guest's first name
        /// </summary>
        public string FirstName { get; set; } = string.Empty;

        /// <summary>
        /// The guest's last name
        /// </summary>
        public string LastName { get; set; } = string.Empty;

        /// <summary>
        /// The guest's email
        /// </summary>
        public string Email { get; set; } = string.Empty;

        /// <summary>
        /// The guest's phone number as a string
        /// </summary>
        public string PhoneNumber {  get; set; } = string.Empty;

        /// <summary>
        /// If the guest has checked in
        /// </summary>
        public bool IsCheckedIn { get; set; } = false;

        /// <summary>
        /// An autogenerated ID number to identify individual guests
        /// </summary>
        public string GuestID { get; set; } = string.Empty;

        /// <summary>
        /// The address of the guest
        /// </summary>
        public string Address { get; set; } = string.Empty;

        /// <summary>
        /// What type of ID the guest used
        /// </summary>
        public IDType IDType { get; set; } = IDType.Other;

        /// <summary>
        /// The number associated with the ID used by the guest
        /// </summary>
        public string IDNumber { get; set; } = string.Empty;



    }
}
